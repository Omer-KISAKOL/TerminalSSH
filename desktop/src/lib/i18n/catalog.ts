export type Messages = typeof messagesTr
export type MessageKey = {
  [K in keyof Messages]: Messages[K] extends string
    ? K
    : {
        [K2 in keyof Messages[K]]: Messages[K][K2] extends string
          ? `${K & string}.${K2 & string}`
          : never
      }[keyof Messages[K]]
}[keyof Messages]